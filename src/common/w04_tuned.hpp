// -----------------------------------------------------------------------------
// W04 ATTENTION — default tile and warps of the tunable GPU stages (P5, E7)
//
// One entry per (stage, tuned N). A binary run without --br/--bc/--warps takes
// the entry whose N is nearest to its --n (ties go to the smaller N), so with
// entries at N = 2048 and 4096, n <= 3072 uses the 2048 entry (decision C29).
//
// Field rules (applied in w04_gpu_stage.cuh):
//   * --br and --bc that are not given come from the entry;
//   * --warps that is not given comes from the entry only if neither --br nor
//     --bc was given; otherwise it is the stage's native warp count for that
//     tile (S2b: 8, S3: Br/16), so explicit tiles keep their P3/P4 meaning.
//
// tools/w04_e7_select.py --write-header replaces everything between the
// BEGIN and END markers (provenance comment and table) with the measured
// selection.
// -----------------------------------------------------------------------------
#pragma once

#include <cstddef>
#include <cstring>

namespace w04 {

struct TunedConfig {
    const char* stage_id;
    std::size_t n;   // N the entry was tuned at
    int br, bc, warps;
};

// BEGIN TUNED TABLE (generated by tools/w04_e7_select.py --write-header)
// Provenance: E7 autotune, run results/raw/W04_ATTENTION/20261106-031127, git_sha 20ddcc38fe95;
//   final median runtime (BH=8, d=64, normal input) of each selected config:
//   GPU_S2b_SWOPT_FUSED N=2048: 64x32 W4 2.9528 ms
//   GPU_S2b_SWOPT_FUSED N=4096: 64x32 W4 12.4019 ms
//   GPU_S3_HWACC_TENSOR_CORE_FP16 N=2048: 64x32 W4 0.6449 ms
//   GPU_S3_HWACC_TENSOR_CORE_FP16 N=4096: 64x64 W4 2.5023 ms
//   GPU_S3_HWACC_TENSOR_CORE_TF32 N=2048: 64x32 W4 1.4433 ms
//   GPU_S3_HWACC_TENSOR_CORE_TF32 N=4096: 64x32 W4 5.6111 ms
inline constexpr TunedConfig kTunedConfigs[] = {
    {"W04_ATTENTION_GPU_S2b_SWOPT_FUSED", 2048, 64, 32, 4},
    {"W04_ATTENTION_GPU_S2b_SWOPT_FUSED", 4096, 64, 32, 4},
    {"W04_ATTENTION_GPU_S3_HWACC_TENSOR_CORE_FP16", 2048, 64, 32, 4},
    {"W04_ATTENTION_GPU_S3_HWACC_TENSOR_CORE_FP16", 4096, 64, 64, 4},
    {"W04_ATTENTION_GPU_S3_HWACC_TENSOR_CORE_TF32", 2048, 64, 32, 4},
    {"W04_ATTENTION_GPU_S3_HWACC_TENSOR_CORE_TF32", 4096, 64, 32, 4},
};
// END TUNED TABLE

// The entry for stage_id nearest to n, or nullptr if the stage has none.
inline const TunedConfig* tuned_config(const char* stage_id, std::size_t n) {
    const TunedConfig* best = nullptr;
    std::size_t best_dist = 0;
    for (const TunedConfig& c : kTunedConfigs) {
        if (std::strcmp(c.stage_id, stage_id) != 0) continue;
        const std::size_t dist = c.n > n ? c.n - n : n - c.n;
        if (best == nullptr || dist < best_dist || (dist == best_dist && c.n < best->n)) {
            best = &c;
            best_dist = dist;
        }
    }
    return best;
}

}  // namespace w04
